-- =========================================
-- ATHENA DATABASE SCHEMA
-- PostgreSQL
-- =========================================

-- 1. Roles
CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE
);

-- 2. Users
CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Day 4 (BalanceVault): when the user last changed their password. Tokens
-- issued before it are refused, so a password change ends every session.
ALTER TABLE app_users
    ADD COLUMN IF NOT EXISTS password_changed_at TIMESTAMPTZ;

-- 3. User roles
CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    role_id BIGINT NOT NULL REFERENCES roles(id),
    PRIMARY KEY (user_id, role_id)
);

-- 4. Bank accounts
CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(id),
    account_number VARCHAR(30) NOT NULL UNIQUE,
    balance NUMERIC(19,2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    account_type VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_account_balance CHECK (balance >= 0),
    CONSTRAINT chk_account_status
        CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    CONSTRAINT chk_account_type
        CHECK (account_type IN ('CUSTOMER', 'SETTLEMENT'))
);

-- Upgrade for databases created before account_type existed (no-op otherwise).
ALTER TABLE accounts
    ADD COLUMN IF NOT EXISTS account_type VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER'
        CONSTRAINT chk_account_type
            CHECK (account_type IN ('CUSTOMER', 'SETTLEMENT'));

-- The bank's cash: the other side of every deposit and withdrawal. Only one may exist.
CREATE UNIQUE INDEX IF NOT EXISTS uq_accounts_single_settlement
    ON accounts (account_type)
    WHERE account_type = 'SETTLEMENT';

-- 5. Financial transactions
CREATE TABLE IF NOT EXISTS financial_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    from_account_id BIGINT REFERENCES accounts(id),
    to_account_id BIGINT REFERENCES accounts(id),
    amount NUMERIC(19,2) NOT NULL,
    idempotency_key VARCHAR(100),
    request_hash VARCHAR(255),
    created_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    failure_code VARCHAR(50),
    failure_reason TEXT,

    CONSTRAINT chk_transaction_amount CHECK (amount > 0),

    CONSTRAINT chk_transaction_type
        CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),

    CONSTRAINT chk_transaction_status
        CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),

    CONSTRAINT chk_transaction_accounts CHECK (
        (transaction_type = 'DEPOSIT'
            AND from_account_id IS NULL
            AND to_account_id IS NOT NULL)
        OR
        (transaction_type = 'WITHDRAWAL'
            AND from_account_id IS NOT NULL
            AND to_account_id IS NULL)
        OR
        (transaction_type = 'TRANSFER'
            AND from_account_id IS NOT NULL
            AND to_account_id IS NOT NULL
            AND from_account_id <> to_account_id)
    )
);

-- Day 3 upgrade (no-op on new databases):
-- idempotency keys are unique per user rather than across all users, and a
-- rejected attempt keeps a machine-readable failure code.
ALTER TABLE financial_transactions
    DROP CONSTRAINT IF EXISTS financial_transactions_idempotency_key_key;

ALTER TABLE financial_transactions
    ADD COLUMN IF NOT EXISTS failure_code VARCHAR(50);

CREATE UNIQUE INDEX IF NOT EXISTS uq_transactions_user_idempotency_key
    ON financial_transactions (created_by, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

-- 6. Double-entry ledger
CREATE TABLE IF NOT EXISTS ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL
        REFERENCES financial_transactions(id),
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    entry_type VARCHAR(10) NOT NULL,
    amount NUMERIC(19,2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_entry_type
        CHECK (entry_type IN ('DEBIT', 'CREDIT')),

    CONSTRAINT chk_ledger_amount CHECK (amount > 0)
);

-- 7. Audit logs
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES app_users(id),
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(50),
    entity_id BIGINT,
    outcome VARCHAR(20),
    details JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_audit_outcome
        CHECK (outcome IN ('COMPLETED', 'FAILED', 'REJECTED', 'REPLAYED', 'DENIED', 'ERROR'))
);

-- Day 3 upgrade (no-op on new databases).
ALTER TABLE audit_logs
    ADD COLUMN IF NOT EXISTS outcome VARCHAR(20)
        CONSTRAINT chk_audit_outcome
            CHECK (outcome IN ('COMPLETED', 'FAILED', 'REJECTED', 'REPLAYED', 'DENIED', 'ERROR'));

CREATE INDEX IF NOT EXISTS idx_audit_created_at
    ON audit_logs(created_at);

-- 7b. Signed-out access tokens (Day 4). A JWT stays valid until it expires,
-- so logout stores its id (jti) here and the API refuses it. Rows whose token
-- has expired are deleted on the next logout.
CREATE TABLE IF NOT EXISTS revoked_tokens (
    jti VARCHAR(64) PRIMARY KEY,
    user_id BIGINT REFERENCES app_users(id),
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_revoked_tokens_expires_at
    ON revoked_tokens(expires_at);

-- 8. Indexes
CREATE INDEX IF NOT EXISTS idx_accounts_user_id
    ON accounts(user_id);

CREATE INDEX IF NOT EXISTS idx_transactions_from_account
    ON financial_transactions(from_account_id);

CREATE INDEX IF NOT EXISTS idx_transactions_to_account
    ON financial_transactions(to_account_id);

CREATE INDEX IF NOT EXISTS idx_transactions_created_at
    ON financial_transactions(created_at);

CREATE INDEX IF NOT EXISTS idx_ledger_transaction
    ON ledger_entries(transaction_id);

CREATE INDEX IF NOT EXISTS idx_ledger_account
    ON ledger_entries(account_id);

CREATE INDEX IF NOT EXISTS idx_audit_actor
    ON audit_logs(actor_id);

-- 9. Double-entry guarantee
-- When a database transaction commits, every financial transaction it wrote
-- ledger entries for must have equal debit and credit totals. The trigger is
-- deferred so it runs at commit, after both sides have been written.
-- The function body uses single quotes because Spring's SQL script runner
-- does not understand $$ quoting; '' inside it is an escaped quote.
CREATE OR REPLACE FUNCTION athena_assert_transaction_balanced()
RETURNS TRIGGER
LANGUAGE plpgsql
AS '
DECLARE
    total_debits  NUMERIC;
    total_credits NUMERIC;
BEGIN
    SELECT COALESCE(SUM(amount) FILTER (WHERE entry_type = ''DEBIT''), 0),
           COALESCE(SUM(amount) FILTER (WHERE entry_type = ''CREDIT''), 0)
      INTO total_debits, total_credits
      FROM ledger_entries
     WHERE transaction_id = NEW.transaction_id;

    IF total_debits <> total_credits THEN
        RAISE EXCEPTION ''Unbalanced ledger for transaction %: debits % do not equal credits %'',
            NEW.transaction_id, total_debits, total_credits
            USING ERRCODE = ''check_violation'';
    END IF;

    RETURN NULL;
END;
';

DROP TRIGGER IF EXISTS trg_ledger_entries_balanced ON ledger_entries;

CREATE CONSTRAINT TRIGGER trg_ledger_entries_balanced
    AFTER INSERT ON ledger_entries
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION athena_assert_transaction_balanced();

-- The project was renamed from LedgerLine to Athena. In a database created
-- before that, the trigger above now uses the new function; drop the old one.
DROP FUNCTION IF EXISTS ledgerline_assert_transaction_balanced();

-- 10. Append-only history
-- Ledger entries, financial transactions and audit records are history: once
-- written they are never changed or deleted, whoever asks. (The app's own
-- database role cannot even ask: see section 11.) Only the schema owner can
-- empty a table with TRUNCATE, which the test suite does between tests.
CREATE OR REPLACE FUNCTION athena_refuse_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS '
BEGIN
    RAISE EXCEPTION ''% is append-only: % is not allowed'', TG_TABLE_NAME, TG_OP;
END;
';

DROP TRIGGER IF EXISTS trg_ledger_entries_append_only ON ledger_entries;
CREATE TRIGGER trg_ledger_entries_append_only
    BEFORE UPDATE OR DELETE ON ledger_entries
    FOR EACH ROW
    EXECUTE FUNCTION athena_refuse_change();

DROP TRIGGER IF EXISTS trg_financial_transactions_append_only ON financial_transactions;
CREATE TRIGGER trg_financial_transactions_append_only
    BEFORE UPDATE OR DELETE ON financial_transactions
    FOR EACH ROW
    EXECUTE FUNCTION athena_refuse_change();

DROP TRIGGER IF EXISTS trg_audit_logs_append_only ON audit_logs;
CREATE TRIGGER trg_audit_logs_append_only
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW
    EXECUTE FUNCTION athena_refuse_change();

-- 11. Least privilege
-- The app connects as its own login role (DB_USERNAME, normally athena_app),
-- a member of the group role athena_writer; this script runs as the schema
-- owner (DB_OWNER_USERNAME). athena_writer may read, add rows, and change
-- only what the app changes (balances, account and user status, passwords,
-- signed-out tokens). It has no UPDATE or DELETE on the history tables, no
-- TRUNCATE, and cannot create, change or drop anything. The app creates both
-- roles at startup (DatabaseRolesProvisioner); if they do not exist, as when
-- one user does everything, nothing below runs.
DO '
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = ''athena_writer'') THEN
        REVOKE ALL ON ALL TABLES IN SCHEMA public FROM athena_writer;
        GRANT USAGE ON SCHEMA public TO athena_writer;
        GRANT SELECT ON roles TO athena_writer;
        GRANT SELECT, INSERT, UPDATE ON app_users, accounts TO athena_writer;
        GRANT SELECT, INSERT ON user_roles, financial_transactions, ledger_entries, audit_logs TO athena_writer;
        GRANT SELECT, INSERT, DELETE ON revoked_tokens TO athena_writer;
        GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO athena_writer;
    END IF;
END';
